/**
 * Asterisk integration layer.
 *
 * - Configuration generation: turns the database into real Asterisk config
 *   files (pjsip.conf, extensions.conf, queues.conf, voicemail.conf, ...).
 * - Dialplan tracing: explains how a dialled number resolves, without
 *   touching a live PBX.
 * - Optional AMI client: live uptime/channel data when an AMI endpoint is
 *   configured; purely simulated telemetry otherwise.
 */
import net from 'node:net';
import os from 'node:os';
import { getDb, getSetting } from './db.js';

const HEADER = (file) => `; ${file}\n; Generated by Asterisk Console — do not edit by hand.\n; Change values in the web interface and re-apply instead.\n\n`;

/**
 * Read the rows of a table that take part in config generation. Tables without
 * an `enabled` column (time groups) are included in full.
 */
const rows = (table, where = null, order = 'id') => {
  const db = getDb();
  const columns = db.prepare(`PRAGMA table_info(${table})`).all().map((c) => c.name);
  const clause = where || (columns.includes('enabled') ? 'enabled = 1' : '1 = 1');
  const orderBy = columns.includes(order) ? order : columns.includes('id') ? 'id' : 'rowid';
  return db.prepare(`SELECT * FROM ${table} WHERE ${clause} ORDER BY ${orderBy}`).all();
};

const truthy = (v) => v === 1 || v === true || v === '1' || v === 'true';

function destinationContext(type, value, entityRows) {
  switch (type) {
    case 'extension':
      return `Goto(from-internal,${value},1)`;
    case 'ring_group':
      return `Goto(ringgroup-${value},s,1)`;
    case 'queue':
      return `Queue(${value},tT)`;
    case 'ivr':
      return `Goto(ivr-${value},s,1)`;
    case 'time_condition':
      return `Goto(timecondition-${value},s,1)`;
    case 'announcement': {
      const rec = entityRows.announcements?.find((a) => String(a.number) === String(value));
      return rec ? `Playback(custom/${rec.recording})` : `Playback(custom/${value})`;
    }
    case 'voicemail':
      return `VoiceMail(${value}@default)`;
    case 'conference':
      return `ConfBridge(${value})`;
    case 'parking':
      return 'Park()';
    case 'disa':
      return `Goto(disa-${value},s,1)`;
    case 'misc': {
      const misc = entityRows.misc_destinations?.find((m) => String(m.number) === String(value));
      return misc ? `Goto(${misc.context},${misc.extension || 's'},1)` : `NoOp(Unmapped misc destination ${value})`;
    }
    case 'terminate':
      return 'Hangup()';
    default:
      return `NoOp(No destination configured)`;
  }
}

/** Asterisk pattern → RegExp (X, Z, N, . and [..] classes). */
export function patternToRegExp(pattern) {
  let src = '';
  for (const ch of String(pattern)) {
    if (ch === 'X') src += '[0-9]';
    else if (ch === 'Z') src += '[1-9]';
    else if (ch === 'N') src += '[2-9]';
    else if (ch === '.') src += '[0-9]+';
    else if (ch === '!') src += '[0-9]*';
    else src += ch.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`^${src}$`);
}

export function generateConfigs() {
  const db = getDb();
  const data = {
    extensions: rows('extensions'),
    trunks: rows('trunks'),
    inbound: rows('inbound_routes'),
    outbound: rows('outbound_routes'),
    ringGroups: rows('ring_groups'),
    queues: rows('queues'),
    ivrs: rows('ivrs'),
    timeConditions: rows('time_conditions'),
    timeGroups: rows('time_groups'),
    announcements: rows('announcements'),
    conferences: rows('conferences'),
    paging: rows('paging'),
    voicemail: rows('voicemail'),
    parking: rows('parking'),
    disa: rows('disa'),
    misc: rows('misc_destinations'),
    featureCodes: rows('feature_codes'),
    music: rows('music'),
    dahdi: rows('dahdi')
  };

  const files = [];
  const warnings = [];

  // ---------------------------------------------------------------- pjsip.conf
  let pjsip = HEADER('pjsip.conf');
  pjsip += '; Generated from Extensions and Trunks\n\n[global]\ntype=global\nendpoint_identifier_order=ip,username,anonymous\n\n';
  for (const ext of data.extensions) {
    if (ext.tech !== 'pjsip') continue;
    const secret = ext.secret || `auto-${ext.extension}`;
    if (!ext.secret) warnings.push(`Extension ${ext.extension} has no secret; a placeholder was generated.`);
    pjsip += `; --- Extension ${ext.extension} (${ext.name}) ---\n`;
    pjsip += `[${ext.extension}]\ntype=endpoint\ncontext=${ext.context || 'from-internal'}\ndisallow=all\n`;
    for (const codec of String(ext.codecs || 'ulaw,alaw').split(',').map((c) => c.trim()).filter(Boolean)) {
      pjsip += `allow=${codec}\n`;
    }
    pjsip += `auth=${ext.extension}\naors=${ext.extension}\ncallerid="${ext.name}" <${ext.extension}>\n`;
    if (ext.recording === 'always') pjsip += 'call_record=yes\n';
    if (ext.outbound_cid) pjsip += `outbound_cid=${ext.outbound_cid}\n`;
    pjsip += '\n';
    pjsip += `[${ext.extension}]\ntype=auth\nauth_type=userpass\nusername=${ext.extension}\npassword=${secret}\n\n`;
    pjsip += `[${ext.extension}]\ntype=aor\nmax_contacts=${ext.max_contacts || 3}\nremove_existing=yes\n\n`;
  }
  for (const trunk of data.trunks) {
    if (trunk.tech !== 'pjsip') continue;
    const name = String(trunk.name).replace(/[^A-Za-z0-9_-]/g, '_');
    pjsip += `; --- Trunk ${name} ---\n[${name}]\ntype=endpoint\ncontext=${trunk.context || 'from-trunk'}\ndisallow=all\n`;
    for (const codec of String(trunk.codecs || 'ulaw,alaw').split(',').map((c) => c.trim()).filter(Boolean)) {
      pjsip += `allow=${codec}\n`;
    }
    pjsip += `outbound_auth=${name}\naors=${name}\nfrom_user=${trunk.from_user || trunk.username || name}\nfrom_domain=${trunk.from_domain || trunk.host}\n\n`;
    if (trunk.secret) {
      pjsip += `[${name}]\ntype=auth\nauth_type=userpass\nusername=${trunk.username || name}\npassword=${trunk.secret}\n\n`;
    }
    pjsip += `[${name}]\ntype=aor\ncontact=sip:${trunk.host}:${trunk.port || 5060}\n\n`;
    if (truthy(trunk.registration)) {
      pjsip += `[${name}]\ntype=registration\nserver_uri=sip:${trunk.host}:${trunk.port || 5060}\nclient_uri=sip:${trunk.username || name}@${trunk.host}\n`;
      pjsip += `outbound_auth=${name}\nretry_interval=60\n\n`;
    }
    if (trunk.cid_prefix) {
      pjsip += `[${name}]\ntype=identify\nendpoint=${name}\nmatch=${trunk.host}\n\n`;
    }
  }
  files.push({ name: 'pjsip.conf', content: pjsip, module: 'Connectivity' });

  // ----------------------------------------------------------- extensions.conf
  let ext = HEADER('extensions.conf');
  ext += '; Generated from Inbound/Outbound Routes, Ring Groups, Queues, IVR, Time Conditions\n\n';

  ext += '[general]\nstatic=yes\nwriteprotect=no\nclearglobalvars=no\n\n';
  ext += '[globals]\nTRUNK_CONTEXT=from-trunk\n\n';

  ext += '[from-internal]\n';
  for (const e of data.extensions) {
    const tech = e.tech === 'pjsip' ? 'PJSIP' : e.tech === 'iax2' ? 'IAX2' : 'SIP';
    ext += `exten => ${e.extension},1,NoOp(Calling extension ${e.extension} - ${e.name})\n`;
    ext += ` same => n,Dial(${tech}/${e.extension},${e.ring_time || 20})\n`;
    if (truthy(e.voicemail)) {
      ext += ` same => n,VoiceMail(${e.extension}@default,u)\n`;
    }
    ext += ' same => n,Hangup()\n\n';
  }
  for (const code of data.featureCodes) {
    const action = {
      call_parking: 'Park()',
      pickup: 'Pickup()',
      blind_transfer: 'NoOp(Blind transfer)',
      attended_transfer: 'NoOp(Attended transfer)',
      voicemail: `VoiceMailMain(\${CALLERID(num)}@default)`,
      disconnect: 'Hangup()',
      automon: 'Monitor(wav,${UNIQUEID},m)',
      parking_announce: 'NoOp(Parking announcement)'
    }[code.feature] || 'NoOp()';
    ext += `exten => ${code.code},1,${action}\n`;
  }
  ext += '\n';
  for (const rg of data.ringGroups) {
    const members = String(rg.members || '').split(',').map((m) => `PJSIP/${m.trim()}`).filter((m) => m !== 'PJSIP/');
    ext += `[ringgroup-${rg.number}]\nexten => s,1,NoOp(Ring group ${rg.number} - ${rg.name})\n`;
    if (rg.strategy === 'hunt' || rg.strategy === 'memoryhunt') {
      members.forEach((m, i) => {
        ext += ` same => n${i === 0 ? '' : ''},Dial(${m},${rg.ring_time || 20})\n`;
      });
    } else {
      ext += ` same => n,Dial(${members.join('&')},${rg.ring_time || 20})\n`;
    }
    ext += ' same => n,Hangup()\n\n';
  }
  for (const q of data.queues) {
    ext += `[queue-${q.number}]\nexten => s,1,Answer()\n same => n,Queue(${q.number},tT,,,${q.timeout || 15})\n same => n,Hangup()\n\n`;
  }
  for (const ivr of data.ivrs) {
    ext += `[ivr-${ivr.number}]\nexten => s,1,Answer()\n`;
    if (ivr.greeting) ext += ` same => n,Playback(custom/${ivr.greeting})\n`;
    ext += ` same => n,WaitExten(${ivr.timeout || 10})\n`;
    let options = [];
    try {
      options = typeof ivr.options === 'string' ? JSON.parse(ivr.options || '[]') : ivr.options || [];
    } catch {
      warnings.push(`IVR ${ivr.number} has invalid menu JSON; entries were skipped.`);
    }
    for (const opt of options) {
      ext += `exten => ${opt.key},1,${destinationContext(opt.type, opt.target, data)}\n`;
    }
    ext += `exten => i,1,${destinationContext(ivr.invalid_destination_type, ivr.invalid_destination, data)}\n`;
    ext += `exten => t,1,${destinationContext(ivr.invalid_destination_type, ivr.invalid_destination, data)}\n\n`;
  }
  for (const tc of data.timeConditions) {
    // Relation ids may come back as "1" or "1.0" depending on storage affinity.
    const group = data.timeGroups.find((g) => Number(g.id) === Number(tc.time_group));
    let ranges = [];
    try {
      ranges = typeof group?.ranges === 'string' ? JSON.parse(group.ranges || '[]') : group?.ranges || [];
    } catch {
      warnings.push(`Time group ${tc.time_group} has invalid JSON.`);
    }
    ext += `[timecondition-${tc.number}]\nexten => s,1,NoOp(Time condition ${tc.name})\n`;
    if (ranges.length === 0) {
      ext += ` same => n,${destinationContext(tc.true_destination_type, tc.true_destination, data)}\n`;
    }
    for (const r of ranges) {
      const [start, end] = [r.start || '00:00', r.end || '23:59'];
      ext += ` same => n,GotoIfTime(${start}-${end},${r.days || '*'},*,*?tc-match)\n`;
    }
    if (ranges.length) {
      ext += ` same => n,${destinationContext(tc.false_destination_type, tc.false_destination, data)}\n`;
      ext += ` same => n(tc-match),${destinationContext(tc.true_destination_type, tc.true_destination, data)}\n`;
    }
    ext += '\n';
  }
  for (const a of data.announcements) {
    ext += `[announce-${a.number}]\nexten => s,1,Answer()\n same => n,Playback(custom/${a.recording})\n`;
    ext += truthy(a.return_after) ? ' same => n,Return()\n\n' : ' same => n,Hangup()\n\n';
  }
  for (const c of data.conferences) {
    ext += `[conference-${c.number}]\nexten => s,1,Answer()\n same => n,ConfBridge(${c.number})\n same => n,Hangup()\n\n`;
  }
  for (const p of data.paging) {
    const members = String(p.members || '').split(',').map((m) => `PJSIP/${m.trim()}`).filter((m) => m !== 'PJSIP/');
    ext += `[paging-${p.number}]\nexten => s,1,Page(${members.join('&')})\n same => n,Hangup()\n\n`;
  }
  for (const d of data.disa) {
    ext += `[disa-${d.number}]\nexten => s,1,Answer()\n same => n,Authenticate(${d.pin || '0000'})\n same => n,DISA(no-password,${d.context || 'from-internal'})\n same => n,Hangup()\n\n`;
  }
  for (const m of data.misc) {
    ext += `[misc-${m.number}]\nexten => s,1,Goto(${m.context},${m.extension || 's'},1)\n\n`;
  }

  // Outbound routes: emergency first, then declaration order.
  const orderedOutbound = [...data.outbound].sort((a, b) => Number(truthy(b.emergency)) - Number(truthy(a.emergency)));
  for (const route of orderedOutbound) {
    const ctx = `outbound-${String(route.name).toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;
    ext += `[${ctx}]\n`;
    const patterns = String(route.patterns || '').split(/[,\n]/).map((p) => p.trim()).filter(Boolean);
    const trunks = String(route.trunks || '').split(',').map((t) => t.trim()).filter(Boolean);
    const trunkTech = trunks.map((t) => `PJSIP/${String(t).replace(/[^A-Za-z0-9_-]/g, '_')}`).join('&');
    for (const pattern of patterns) {
      const match = /^[_]?/.test(pattern) ? `_${pattern.replace(/^_/, '')}` : `_${pattern}`;
      ext += `exten => ${match},1,NoOp(Outbound ${route.name} matched \${EXTEN})\n`;
      if (route.prefix) ext += ` same => n,Set(num=\${EXTEN:${String(route.prefix).length}})\n`;
      else ext += ' same => n,Set(num=${EXTEN})\n';
      if (route.prepend) ext += ` same => n,Set(num=${route.prepend}\${num})\n`;
      if (route.callerid) ext += ` same => n,Set(CALLERID(num)=${route.callerid})\n`;
      ext += ` same => n,Dial(${trunkTech}/\${num},60)\n same => n,Hangup()\n\n`;
    }
    ext += '\n';
  }
  // Inbound routes.
  ext += '[from-trunk]\n';
  for (const r of data.inbound) {
    const didPattern = /^[_]/.test(r.did) ? r.did : `_${r.did}`;
    ext += `exten => ${didPattern},1,NoOp(Inbound ${r.description || r.did})\n`;
    ext += ` same => n,GotoIf($["\${CALLERID(num)}" = ""]?nodid:check)\n`;
    ext += ` same => n(nodid),NoOp(No caller ID)\n`;
    if (truthy(r.privacy)) ext += ' same => n,Hangup()\n';
    ext += ` same => n(check),${destinationContext(r.destination_type, r.destination, data)}\n same => n,Hangup()\n\n`;
  }
  if (data.inbound.length === 0) ext += 'exten => _X.,1,Hangup()\n';
  ext += '\n[from-pstn]\ninclude => from-trunk\n';
  files.push({ name: 'extensions.conf', content: ext, module: 'Connectivity' });

  // -------------------------------------------------------------- queues.conf
  let queues = HEADER('queues.conf');
  for (const q of data.queues) {
    queues += `[${q.number}]\n`;
    queues += `strategy=${q.strategy || 'ringall'}\n`;
    queues += `timeout=${q.timeout || 15}\nretry=${q.retry || 5}\n`;
    queues += `maxlen=${q.maxlen || 0}\nweight=${q.weight || 0}\n`;
    queues += `joinempty=${q.joinempty || 'yes'}\nleavewhenempty=${q.leavewhenempty || 'no'}\n`;
    queues += `musicclass=${q.music || 'default'}\n`;
    queues += 'monitor_format=wav\n\n';
  }
  files.push({ name: 'queues.conf', content: queues, module: 'Applications' });

  // ----------------------------------------------------------- voicemail.conf
  let vm = HEADER('voicemail.conf');
  vm += '[general]\nformat=wav49|gsm|wav\nserveremail=asterisk@localhost\nattach=yes\nmaxmsg=100\n';
  vm += 'maxsecs=180\nminsecs=2\nsaycid=no\nsayduration=no\nemaildateformat=%A, %B %d, %Y at %r\n\n';
  vm += '[default]\n';
  for (const box of data.voicemail) {
    const opts = [box.pin || '0000', box.name || box.mailbox];
    if (box.email) opts.push(box.email);
    if (truthy(box.attach)) opts.push('attach=yes');
    if (truthy(box.delete_after_email)) opts.push('delete=yes');
    vm += `${box.mailbox} => ${opts.join(',')},maxmsg=${box.max_messages || 100}\n`;
  }
  files.push({ name: 'voicemail.conf', content: vm, module: 'Applications' });

  // ------------------------------------------------------------ features.conf
  let features = HEADER('features.conf');
  features += '[general]\nfeaturedigittimeout=1000\n\n[featuremap]\n';
  for (const code of data.featureCodes) {
    const key = {
      call_parking: 'parkcall',
      blind_transfer: 'blindxfer',
      attended_transfer: 'atxfer',
      disconnect: 'disconnect',
      automon: 'automon'
    }[code.feature];
    if (key) features += `${key} => ${code.code}\n`;
  }
  features += '\n[applicationmap]\n';
  files.push({ name: 'features.conf', content: features, module: 'Settings' });

  // ------------------------------------------------------- musiconhold.conf
  let moh = HEADER('musiconhold.conf');
  for (const m of data.music) {
    moh += `[${m.name}]\nmode=${m.mode || 'files'}\ndirectory=${m.path || '/var/lib/asterisk/moh'}\n`;
    if (m.sort) moh += `sort=${m.sort}\n`;
    moh += '\n';
  }
  files.push({ name: 'musiconhold.conf', content: moh, module: 'Settings' });

  // ---------------------------------------------------------------- dahdi.conf
  if (data.dahdi.length) {
    let dahdi = HEADER('chan_dahdi.conf');
    dahdi += '[trunkgroups]\n\n[channels]\n';
    for (const c of data.dahdi) {
      dahdi += `; channel ${c.channel} — ${c.description || ''}\n`;
      dahdi += `signalling=${c.signalling}\n`;
      dahdi += `context=${c.context || 'from-pstn'}\n`;
      dahdi += `group=${c.group || 0}\nchannel=>${c.channel}\n\n`;
    }
    files.push({ name: 'chan_dahdi.conf', content: dahdi, module: 'Connectivity' });
  }

  // Legacy chan_sip / IAX2 devices still need those drivers.
  const legacySip = data.extensions.filter((e) => e.tech === 'sip');
  if (legacySip.length) {
    let sip = HEADER('sip_additional.conf');
    for (const e of legacySip) {
      sip += `[${e.extension}]\ntype=friend\nsecret=${e.secret || `auto-${e.extension}`}\ncontext=${e.context || 'from-internal'}\nhost=dynamic\ncallerid="${e.name}" <${e.extension}>\n\n`;
    }
    warnings.push(`${legacySip.length} extension(s) use chan_sip, which is deprecated in Asterisk 21+. Migrate them to PJSIP.`);
    files.push({ name: 'sip_additional.conf', content: sip, module: 'Connectivity' });
  }

  const totalLines = files.reduce((n, f) => n + f.content.split('\n').length, 0);
  return {
    generatedAt: new Date().toISOString(),
    files,
    warnings,
    summary: {
      files: files.length,
      lines: totalLines,
      extensions: data.extensions.length,
      trunks: data.trunks.length,
      inboundRoutes: data.inbound.length,
      outboundRoutes: data.outbound.length,
      queues: data.queues.length,
      ivrs: data.ivrs.length
    }
  };
}

/** Trace how a dialled number resolves — the "dialplan test" feature. */
export function testDialplan(number, callerId = '') {
  const db = getDb();
  const digits = String(number || '').replace(/[^0-9*#+]/g, '');
  const steps = [];
  const push = (step, detail, extra = {}) => steps.push({ step, detail, ...extra });

  if (!digits) {
    return { number, matched: false, steps: [{ step: 'input', detail: 'Enter a number to test', status: 'error' }], destination: null };
  }

  push('input', `Dialled ${digits}${callerId ? ` from ${callerId}` : ''}`, { status: 'info' });

  // 1. Internal extension?
  const ext = db.prepare('SELECT * FROM extensions WHERE extension = ?').get(Number(digits) || -1);
  if (ext) {
    push('internal', `Extension ${ext.extension} — ${ext.name}`, { status: 'ok' });
    push('dial', `Dial(PJSIP/${ext.extension}, ${ext.ring_time || 20}s)${truthy(ext.voicemail) ? `, then VoiceMail(${ext.extension}@default)` : ''}`, { status: 'match' });
    return {
      number: digits,
      matched: true,
      type: 'extension',
      destination: `Extension ${ext.extension} (${ext.name})`,
      enabled: truthy(ext.enabled),
      steps
    };
  }

  // 2. Ring group / queue / IVR / feature code by number.
  const lookups = [
    ['ring_groups', 'Ring group', 'ringgroup'],
    ['queues', 'Queue', 'queue'],
    ['ivrs', 'IVR', 'ivr'],
    ['conferences', 'Conference', 'conference'],
    ['paging', 'Paging group', 'paging'],
    ['disa', 'DISA', 'disa'],
    ['time_conditions', 'Time condition', 'timecondition'],
    ['announcements', 'Announcement', 'announcement']
  ];
  for (const [table, label, ctx] of lookups) {
    const row = db.prepare(`SELECT * FROM ${table} WHERE number = ?`).get(Number(digits) || -1);
    if (row) {
      push('application', `${label} ${digits} — ${row.name}`, { status: 'ok' });
      push('route', `Goto(${ctx}-${digits},s,1)`, { status: 'match' });
      return {
        number: digits,
        matched: true,
        type: ctx,
        destination: `${label} ${digits} (${row.name})`,
        enabled: truthy(row.enabled),
        steps
      };
    }
  }

  // 3. Feature code?
  const feature = db.prepare('SELECT * FROM feature_codes WHERE code = ?').get(digits);
  if (feature) {
    push('feature', `Feature code ${digits} — ${feature.description || feature.feature}`, { status: 'match' });
    return { number: digits, matched: true, type: 'feature', destination: feature.description || feature.feature, enabled: truthy(feature.enabled), steps };
  }

  // 4. Blacklist short-circuit.
  const blocked = db.prepare('SELECT * FROM blacklist WHERE number = ? AND enabled = 1').get(digits);
  if (blocked) {
    push('blacklist', `Number is blacklisted (${blocked.description || 'no reason recorded'})`, { status: 'error' });
    return { number: digits, matched: false, type: 'blacklist', destination: 'Blocked', enabled: false, steps };
  }

  // 5. Outbound routes in evaluation order (emergency first).
  const routes = db.prepare('SELECT * FROM outbound_routes WHERE enabled = 1').all()
    .sort((a, b) => Number(truthy(b.emergency)) - Number(truthy(a.emergency)));
  for (const route of routes) {
    const patterns = String(route.patterns || '').split(/[,\n]/).map((p) => p.trim()).filter(Boolean);
    for (const pattern of patterns) {
      let re;
      try {
        re = patternToRegExp(pattern);
      } catch {
        continue;
      }
      if (re.test(digits)) {
        push('outbound', `Route "${route.name}" pattern ${pattern} matched`, { status: 'ok' });
        const trunks = String(route.trunks || '').split(',').map((t) => t.trim()).filter(Boolean);
        if (trunks.length === 0) {
          push('error', 'Route has no trunks configured', { status: 'error' });
          return { number: digits, matched: false, type: 'outbound', destination: null, steps };
        }
        push('dial', `Dial(${trunks.map((t) => `PJSIP/${t}`).join('&')}/${digits}, 60)`, { status: 'match' });
        return {
          number: digits,
          matched: true,
          type: 'outbound',
          destination: `${route.name} via ${trunks.join(' → ')}`,
          enabled: true,
          steps
        };
      }
    }
  }

  push('result', 'No matching route. The call would be rejected with "number not found".', { status: 'error' });
  return { number: digits, matched: false, type: null, destination: null, steps };
}

// --------------------------------------------------------------------------
// Optional AMI client (read-only status polling)
// --------------------------------------------------------------------------
let amiState = { connected: false, lastError: null, lastPoll: null, info: {}, channels: [] };

export function amiConfigured() {
  return Boolean(getSetting('ami_host', '') && getSetting('ami_user', ''));
}

function amiAction(action, headers = {}) {
  return new Promise((resolve) => {
    const host = getSetting('ami_host');
    const port = Number(getSetting('ami_port', '5038')) || 5038;
    const user = getSetting('ami_user');
    const secret = getSetting('ami_secret');
    const socket = net.createConnection({ host, port });
    let buffer = '';
    let loggedIn = false;
    let settled = false;
    const finish = (value) => {
      if (settled) return;
      settled = true;
      try { socket.destroy(); } catch {}
      resolve(value);
    };
    socket.setTimeout(4000, () => finish({ error: 'AMI timeout' }));
    socket.on('error', (err) => finish({ error: err.message }));
    socket.on('connect', () => {
      socket.write(`Action: Login\r\nUsername: ${user}\r\nSecret: ${secret}\r\nEvents: off\r\n\r\n`);
    });
    socket.on('data', (chunk) => {
      buffer += chunk.toString('utf8');
      if (!loggedIn && /Response: (Success|Error)/.test(buffer)) {
        if (/Response: Error/.test(buffer)) return finish({ error: buffer.split('\r\n')[0] });
        loggedIn = true;
        buffer = '';
        const payload = `Action: ${action}\r\n${Object.entries(headers).map(([k, v]) => `${k}: ${v}\r\n`).join('')}ActionID: console\r\n\r\n`;
        socket.write(payload);
        return;
      }
      if (loggedIn && buffer.includes('--END COMMAND--') || (loggedIn && /^Response: (Success|Error)/m.test(buffer) && buffer.includes('\r\n\r\n'))) {
        finish({ raw: buffer });
      }
    });
  });
}

export async function refreshAmi() {
  if (!amiConfigured()) {
    amiState = { connected: false, lastError: null, lastPoll: new Date().toISOString(), info: {}, channels: [], simulated: true };
    return amiState;
  }
  const res = await amiAction('CoreStatus');
  if (res.error) {
    amiState = { ...amiState, connected: false, lastError: res.error, lastPoll: new Date().toISOString(), simulated: false };
    return amiState;
  }
  const info = {};
  for (const line of String(res.raw || '').split('\r\n')) {
    const idx = line.indexOf(':');
    if (idx > 0) info[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
  }
  amiState = {
    connected: true,
    lastError: null,
    lastPoll: new Date().toISOString(),
    info,
    channels: amiState.channels,
    simulated: false
  };
  return amiState;
}

export function getAmiState() {
  return amiState;
}

// --------------------------------------------------------------------------
// Host telemetry
// --------------------------------------------------------------------------
export function hostStats() {
  const load = os.loadavg();
  const memTotal = os.totalmem();
  const memFree = os.freemem();
  return {
    hostname: os.hostname(),
    platform: `${os.type()} ${os.release()}`,
    uptimeSeconds: Math.round(os.uptime()),
    processUptimeSeconds: Math.round(process.uptime()),
    cpus: os.cpus().length,
    load1: Number(load[0].toFixed(2)),
    load5: Number(load[1].toFixed(2)),
    load15: Number(load[2].toFixed(2)),
    memoryTotal: memTotal,
    memoryUsed: memTotal - memFree,
    memoryPct: Math.round(((memTotal - memFree) / memTotal) * 100),
    node: process.version
  };
}
